        if column == 2 then fields[#fields + 1] = prefix .. "%5Bsearchable%5D=true" else fields[#fields + 1] = prefix .. "%5Bsearchable%5D=false" end
        fields[#fields + 1] = prefix .. "%5Borderable%5D=true"
