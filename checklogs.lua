    if tonumber(port) ~= PLAYERS_PORT or (ip ~= PLAYERS_SERVER and ip ~= PLAYERS_DOMAIN) then return nil end
    local found, id = sampGetPlayerIdByCharHandle(PLAYER_PED)
    -- Gamestate checks the connection; sampIsPlayerConnected is unreliable for the local player.
    if not found or type(id) ~= "number" or id < 0 or id > MAX_PLAYER_ID then return nil end
    return ip .. ":" .. tostring(port), id
end

local function stopPlayersChecker()
    playersChecker.generation = playersChecker.generation + 1
    playersChecker.busy = false
    playersChecker.server, playersChecker.lastMinute = nil, -1
    -- Уже запущенный запрос отменяется; его callback не может оживить старую сессию.
    for i = #pendingRequests, 1, -1 do
        if pendingRequests[i].playersChecker then
            pcall(pendingRequests[i].runner.cancel, pendingRequests[i].runner)
            table.remove(pendingRequests, i)
        end
    end
end

local function playersToken()
    return mainIni and mainIni.checker and tostring(mainIni.checker.token or "") or ""
end

local function playersRequest(players)
    local server = playersConnection()
    if not server or playersChecker.busy then return end
    local token = playersToken()
    if not token:match("^[a-f0-9]+$") or #token ~= 64 then return end
    local generation = playersChecker.generation
    -- Токен обязателен в каждом отчёте. Адрес/состояние сервера остаются только в Lua.
    local payload = {token = token, players = players}
    playersChecker.busy = true
    playersChecker.nextAttempt = os.time() + 60
    local function current()
        return generation == playersChecker.generation and server == playersConnection() and token == playersToken()
    end
    local function failed()
        if current() then
            playersChecker.busy = false
            -- Не печатаем сетевые ошибки: некоторые HTTP-библиотеки включают тело запроса.
            print("[checklogs] Player checker request failed; retry in 60 seconds.")
        end
    end
    local request = asyncHttpRequest("POST", PLAYERS_URL, {headers = {['Content-Type'] = 'application/json; charset=UTF-8'},
        data = json.encode(payload)}, function(response)
        if not current() then return end
        playersChecker.busy = false
        local ok, result = pcall(json.decode, response.text or "")
        if response.status_code ~= 200 or not ok or type(result) ~= "table" then failed(); return end
        if result.ok ~= true then
            if result.error == "unauthorized" then
                chat("[checklogs] Токен не принят. Получите /gettoken в ЛС группы и введите /settoken [token].")
                playersChecker.nextAttempt = math.huge
            end
            return
        end
        -- GAS проверил токен этого отчёта; отдельной сессии авторизации нет.
        -- Следующий сбор привязан к границе минуты, не к задержке HTTP.
        playersChecker.nextAttempt = 0
    end, failed)
    if request then request.playersChecker = true end
end

local function pollPlayersChecker()
    local server, myId = playersConnection()
    if not server then
        if playersChecker.server or playersChecker.busy then stopPlayersChecker() end
        return
    end
    if server ~= playersChecker.server then
        stopPlayersChecker()
        playersChecker.server, playersChecker.nextAttempt = server, 0
    end
    if playersToken() == "" or playersChecker.busy or os.time() < playersChecker.nextAttempt then return end
    local minute = math.floor(os.time() / 60)
    if minute == playersChecker.lastMinute then return end
    local players, seen = {}, {}
    local function add(id)
        local nick = sampGetPlayerNickname(id)
        if nick and #nick >= 3 and #nick <= 24 and not seen[nick] then
            seen[nick], players[#players + 1] = true, nick
        end
    end
    add(myId)
    for id = 0, math.min(sampGetMaxPlayerId(), MAX_PLAYER_ID) do
        if sampIsPlayerConnected(id) then add(id) end
    end
    -- Проверяем соединение ещё раз после сбора; пустой список после дисконнекта не отправляем.
    if server ~= playersConnection() or #players == 0 then stopPlayersChecker(); return end
    playersChecker.lastMinute, playersChecker.nextAttempt = minute, 0
    playersRequest(players)
end

